// Generates the data format reference from schema/*.schema.json, the source of truth CI
// enforces (docs/SPEC.md, "Docs site"), so the page can never drift from validation.
// Output: src/content/docs/reference/data-format.md (gitignored).
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const site = fileURLToPath(new URL('../', import.meta.url));
const schemaDir = path.join(site, '../schema');
const out = path.join(site, 'src/content/docs/reference/data-format.md');

const KINDS = [
  ['work', 'Works', 'data/works/<id>.yaml'],
  ['sequence', 'Absolute sequences', 'data/sequences/<id>.yaml'],
  ['group', 'Release groups', 'data/groups/<id>.yaml'],
];

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');

/** A short type label for a schema node: refs by name, unions joined, arrays as "list of". */
function typeOf(node) {
  if (!node) return '';
  if (node.$ref) return `[${node.$ref.split('/').pop()}](#${node.$ref.split('/').pop().toLowerCase()})`;
  if (node.anyOf || node.oneOf) return (node.anyOf ?? node.oneOf).map(typeOf).join(' or ');
  if (node.enum) return node.enum.map((v) => `\`${v === null ? 'null' : v}\``).join(', ');
  if (node.const !== undefined) return `\`${node.const}\``;
  if (node.type === 'array') return `list of ${typeOf(node.items)}`;
  if (Array.isArray(node.type)) return node.type.join(' or ');
  if (node.type === 'object' && node.title) return node.title;
  return node.type ?? '';
}

function details(node) {
  const bits = [];
  if (node.pattern) bits.push(`pattern \`${node.pattern}\``);
  if (node.minimum !== undefined) bits.push(`at least ${node.minimum}`);
  if (node.maxLength !== undefined) bits.push(`at most ${node.maxLength} characters`);
  if (node.default !== undefined) bits.push(`default \`${node.default}\``);
  return bits.join(', ');
}

/** A property table for one object schema, then the tables of any titled nested objects. */
function objectSection(node, heading, level, seen) {
  const lines = [];
  const req = new Set(node.required ?? []);
  lines.push(`${'#'.repeat(level)} ${heading}`, '');
  if (node.description) lines.push(node.description, '');
  const props = Object.entries(node.properties ?? {});
  if (props.length > 0) {
    lines.push('| Field | Type | Required | Description |', '| --- | --- | --- | --- |');
    for (const [name, p] of props) {
      const d = [p.description, details(p)].filter(Boolean).join(' ');
      lines.push(`| \`${name}\` | ${cell(typeOf(p))} | ${req.has(name) ? 'yes' : ''} | ${cell(d)} |`);
    }
    lines.push('');
  }
  for (const [, p] of props) {
    const nested = p.type === 'object' && p.title && p.properties ? p : null;
    if (nested && !seen.has(nested.title)) {
      seen.add(nested.title);
      lines.push(...objectSection(nested, nested.title, level + 1, seen));
    }
    const item = p.type === 'array' && p.items?.type === 'object' && p.items.properties ? p.items : null;
    if (item && !seen.has(item.title ?? p)) {
      seen.add(item.title ?? p);
      lines.push(...objectSection(item, item.title ?? 'Item', level + 1, seen));
    }
  }
  return lines;
}

const lines = [
  '---',
  'title: Data format',
  'description: Every field of the YAML files under data/, generated from the JSON Schemas CI validates against.',
  'editUrl: false',
  '---',
  '',
  '<!-- Generated by site/scripts/gen-data-format.mjs from schema/*.schema.json. Do not edit; change the schema instead. -->',
  '',
  'Generated from [`schema/`](https://github.com/courmap/courmap/tree/main/schema), the same JSON Schemas `pnpm validate` checks every file against. For how to use these fields, see [Contributing mappings](/contributing/).',
  '',
];
for (const [kind, title, file] of KINDS) {
  const schema = JSON.parse(await readFile(path.join(schemaDir, `${kind}.schema.json`), 'utf8'));
  lines.push(...objectSection(schema, `${title}: \`${file}\``, 2, new Set()));
  const defs = Object.entries(schema.$defs ?? {});
  if (defs.length > 0) {
    lines.push(`### Shared definitions (${kind})`, '');
    for (const [name, d] of defs) {
      lines.push(`#### ${name}`, '');
      if (d.description) lines.push(d.description, '');
      const t = typeOf(d);
      const extra = details(d);
      if (t || extra) lines.push(`Type: ${t}${extra ? `; ${extra}` : ''}.`, '');
      if (d.properties) {
        lines.push('| Field | Type | Required | Description |', '| --- | --- | --- | --- |');
        const req = new Set(d.required ?? []);
        for (const [n, p] of Object.entries(d.properties)) lines.push(`| \`${n}\` | ${cell(typeOf(p))} | ${req.has(n) ? 'yes' : ''} | ${cell([p.description, details(p)].filter(Boolean).join(' '))} |`);
        lines.push('');
      }
    }
  }
}
await writeFile(out, lines.join('\n') + '\n');
console.log(`data format reference written to ${path.relative(site, out)}`);
