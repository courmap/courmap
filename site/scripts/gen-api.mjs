// Generates the library API reference from the client's TypeScript source with TypeDoc
// (docs/SPEC.md, "Docs site": generated from code, so it cannot drift). Output goes to
// src/content/docs/reference/library/api/, gitignored and rebuilt on every docs build.
import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Application } from 'typedoc';

const site = fileURLToPath(new URL('../', import.meta.url));
const out = path.join(site, 'src/content/docs/reference/library/api');

await rm(out, { recursive: true, force: true });
const app = await Application.bootstrapWithPlugins({
  // TypeDoc reads entry points as globs, which need forward slashes even on Windows.
  entryPoints: [path.join(site, '../packages/client/src/index.ts').split(path.sep).join('/')],
  tsconfig: path.join(site, 'tsconfig.typedoc.json'),
  plugin: ['typedoc-plugin-markdown'],
  out,
  readme: 'none',
  excludePrivate: true,
  excludeInternal: true,
  disableSources: true,
  hidePageHeader: true,
  hideBreadcrumbs: true,
  entryFileName: 'index',
  outputFileStrategy: 'members',
});
const project = await app.convert();
if (!project || app.logger.hasErrors()) throw new Error('TypeDoc could not convert @courmap/client');
await app.generateOutputs(project);

/** Starlight needs a title in frontmatter; TypeDoc writes it as the first heading. */
async function addFrontmatter(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const file = path.join(dir, e.name);
    if (e.isDirectory()) {
      await addFrontmatter(file);
      continue;
    }
    if (!e.name.endsWith('.md')) continue;
    let text = await readFile(file, 'utf8');
    const heading = /^#\s+(.+)$/m.exec(text);
    const title = file === path.join(out, 'index.md') ? 'Library API' : (heading?.[1] ?? e.name.replace(/\.md$/, '')).replace(/\\/g, '').trim();
    if (heading) text = text.replace(heading[0], '');
    // Links point at .md files; Starlight serves each page at a lowercase directory route.
    text = text.replace(/\]\(([^)\s]+?)\.md(#[^)]*)?\)/g, (_m, rel, anchor = '') => {
      const target = path.relative(out, path.resolve(path.dirname(file), rel)).split(path.sep).join('/').toLowerCase();
      return `](/reference/library/api/${target === 'index' ? '' : `${target}/`}${anchor.toLowerCase()})`;
    });
    await writeFile(file, `---\ntitle: ${JSON.stringify(title)}\neditUrl: false\n---\n\n<!-- Generated by site/scripts/gen-api.mjs from packages/client/src. Do not edit. -->\n${text}`);
  }
}
await addFrontmatter(out);
console.log(`API reference written to ${path.relative(site, out)}`);
